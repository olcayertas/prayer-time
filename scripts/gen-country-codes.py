#!/usr/bin/env python3
"""Regenerates the ISO -> EzanVakti country tables for both platforms from
shared/ezanvakti-country-codes.json. Run from the repo root after editing the JSON."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
codes = json.loads((root / "shared/ezanvakti-country-codes.json").read_text())["codes"]
header = "GENERATED by scripts/gen-country-codes.py from shared/ezanvakti-country-codes.json. Do not edit."

swift_rows = "\n".join(f'        "{iso}": "{uid}",' for iso, uid in codes.items())
(root / "apple/Sources/Core/CountryCodes.swift").write_text(f"""// {header}

/// ISO 3166-1 alpha-2 code (as the reverse geocoder reports it) → EzanVakti country id (`UlkeID`).
enum CountryCodes {{
    static let ezanVaktiCountryId: [String: String] = [
{swift_rows}
    ]
}}
""")

kotlin_rows = "\n".join(f'        "{iso}" to "{uid}",' for iso, uid in codes.items())
(root / "android/domain/src/main/kotlin/com/olcayertas/namazvakti/domain/CountryCodes.kt").write_text(f"""// {header}
package com.olcayertas.namazvakti.domain

/** ISO 3166-1 alpha-2 code (as the reverse geocoder reports it) → EzanVakti country id (`UlkeID`). */
object CountryCodes {{
    val ezanVaktiCountryId: Map<String, String> = mapOf(
{kotlin_rows}
    )
}}
""")
print(f"wrote {len(codes)} rows")
